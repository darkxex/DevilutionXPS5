#!/usr/bin/env bash
# Compiles the render driver's shaders (sdl2/shaders/quad.{vert,frag}) to SPIR-V and writes them as C arrays into
# sdl2/ps5vk_shaders.h (committed, so builds don't need a shader compiler).
#
#   GLSLANG=/path/to/glslang bash tools/make-vk-shaders.sh
# SPDX-License-Identifier: GPL-3.0-or-later
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
glslang=${GLSLANG:-$(command -v glslang || command -v glslangValidator)}
dir="$root/sdl2/shaders"
out="$root/sdl2/ps5vk_shaders.h"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

to_c() {
    python3 -c '
import sys, struct
data = open(sys.argv[1], "rb").read()
words = struct.unpack("<%dI" % (len(data) // 4), data)
print("static const uint32_t SPV_%s[] = {" % sys.argv[2].upper())
for i in range(0, len(words), 8):
    print("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
print("};")' "$1" "$2"
}

{
    echo "/* Generated by tools/make-vk-shaders.sh from sdl2/shaders/quad.*. Do not edit. */"
    echo "#ifndef PS5VK_SHADERS_H"
    echo "#define PS5VK_SHADERS_H"
    echo "#include <stdint.h>"
    for src in "$dir"/quad.vert "$dir"/quad.frag; do
        name=$(basename "$src" | tr '.' '_')
        "$glslang" -V --target-env vulkan1.1 -o "$tmp/$name.spv" "$src" >/dev/null
        to_c "$tmp/$name.spv" "$name"
    done
    echo "#endif"
} >"$out"
echo "wrote $out"
